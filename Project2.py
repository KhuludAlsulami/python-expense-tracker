import csv
from datetime import datetime
from tabulate import tabulate

CATEGORIES = ["food", "transportation", "entertainment", "salary", "Electricity bill", "water bill", "accommodation", "shopping"]

class ExpenseTracker:
    def __init__(self):
        self.current_user = None

    def load_transactions(self):
        try:
            with open(f"{self.current_user}_transactions.csv", "r") as file:
                reader = csv.DictReader(file)
                transactions = list(reader)
        except FileNotFoundError:
            transactions = []
        return transactions

    def save_transactions(self, transactions):
        with open(f"{self.current_user}_transactions.csv", "w", newline="") as file:
            writer = csv.DictWriter(file, fieldnames=["Date", "Type", "Category", "Amount"])
            writer.writeheader()
            writer.writerows(transactions)

    def validate_date(self, date_text):
        try:
            datetime.strptime(date_text, "%Y-%m-%d")
            return True
        except ValueError:
            return False

    def add_transaction(self):
        print("\nAdd a New Transaction")
        amount = float(input("Enter the amount: "))

        print("Available Categories:")
        for index, category in enumerate(CATEGORIES, start=1):
            print(f"{index}. {category}")

        category_index = int(input("Enter the index of the category: ")) - 1

        if category_index < 0 or category_index >= len(CATEGORIES):
            print("Invalid category index.")
            return

        category = CATEGORIES[category_index]

        date = input("Enter the date (YYYY-MM-DD): ")
        transaction_type = input("Enter the transaction type (Expense/Income): ")

        if not self.validate_date(date):
            print("Invalid date format. Please use YYYY-MM-DD.")
            return

        if transaction_type.lower() not in ["expense", "income"]:
            print("Invalid transaction type. Please enter 'Expense' or 'Income'.")
            return

        transaction = {"Date": date, "Type": transaction_type.capitalize(), "Category": category, "Amount": amount}
        transactions = self.load_transactions()
        transactions.append(transaction)
        self.save_transactions(transactions)
        print("Transaction added successfully.")

    def view_transactions(self):
        transactions = self.load_transactions()
        if not transactions:
            print("No transactions found.")
            return

        print("\nAll Transactions")
        print(tabulate(transactions, headers="keys"))

    def delete_transaction(self):
        print("\nDelete a Transaction")
        transactions = self.load_transactions()
        if not transactions:
            print("No transactions found.")
            return

        print(tabulate(transactions, headers="keys"))
        index = int(input("Enter the index of the transaction to delete: ")) - 1

        if index < 0 or index >= len(transactions):
            print("Invalid transaction index.")
        else:
            del transactions[index]
            self.save_transactions(transactions)
            print("Transaction deleted successfully.")

    def generate_reports(self):
        transactions = self.load_transactions()
        if not transactions:
            print("No transactions found.")
            return

        total_expenses = 0
        total_income = 0

        for transaction in transactions:
            amount = float(transaction["Amount"])
            if transaction["Type"] == "Expense":
                total_expenses += amount
            elif transaction["Type"] == "Income":
                total_income += amount

        print("\nBasic Reports")
        print("Total Expenses:", total_expenses)
        print("Total Income:", total_income)

        categories = set(transaction["Category"] for transaction in transactions)
        category_spending = {category: sum(float(transaction["Amount"]) for transaction in transactions if transaction["Category"] == category) for category in categories}

        print("\nSpending by Category")
        print(tabulate(category_spending.items(), headers=["Category", "Amount"]))

        print("\nTransactions by Category")
        for category in categories:
            category_transactions = [transaction for transaction in transactions if transaction["Category"] == category]
            print(f"\n{category.capitalize()} Transactions")
            print(tabulate(category_transactions, headers="keys"))

        print("\nAverage Transaction Value by Category")
        avg_transaction_value = {category: sum(float(transaction["Amount"]) for transaction in transactions if transaction["Category"] == category) / len([transaction for transaction in transactions if transaction["Category"] == category]) for category in categories}
        print(tabulate(avg_transaction_value.items(), headers=["Category", "Average Amount"]))

    def manage_tracker(self):
        print(f"\nWelcome, {self.current_user}!")
        while True:
            print("\nOptions:")
            print("1. Add a transaction")
            print("2. View transactions")
            print("3. Delete a transaction")
            print("4. Generate reports")
            print("5. Logout6. Exit")
            choice = input("Enter your choice: ")

            if choice == "1":
                self.add_transaction()
            elif choice == "2":
                self.view_transactions()
            elif choice == "3":
                self.delete_transaction()
            elif choice == "4":
                self.generate_reports()
            elif choice == "5":
                self.current_user = None
                print("Logged out successfully.")
                break
            elif choice == "6":
                print("Exiting...")
                exit()
            else:
                print("Invalid choice. Please try again.")

    def login(self):
        username = input("Enter your username: ")
        self.current_user = username

    def register(self):
        username = input("Enter a username: ")
        self.current_user = username
        self.save_transactions([])

    def main(self):
        while True:
            print("\nExpense Tracker")
            print("1. Login")
            print("2. Register")
            print("3. Exit")
            choice = input("Enter your choice: ")

            if choice == "1":
                self.login()
                if self.current_user is not None:
                    self.manage_tracker()
            elif choice == "2":
                self.register()
                if self.current_user is not None:
                    self.manage_tracker()
            elif choice == "3":
                print("Exiting...")
                break
            else:
                print("Invalid choice. Please try again.")

tracker = ExpenseTracker()
tracker.main()